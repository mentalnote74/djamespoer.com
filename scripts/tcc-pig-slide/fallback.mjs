// Complete static previews from approved registered pixels; no generated artwork.
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
const magick = process.env.IMAGEMAGICK ?? 'C:/Program Files/ImageMagick-7.1.2-Q16-HDRI/magick.exe';
execFileSync(process.execPath, ['scripts/tcc-pig-slide/prepare.mjs'], { stdio: 'inherit' });
const previews = {};
for (const pose of ['rest', 'kiss']) {
  const file = `tmp/tcc-pig/fallback-${pose}-384.webp`;
  execFileSync(magick, [
    'tmp/tcc-pig/base.png',
    'tmp/tcc-pig/eye-open.png',
    '-compose',
    'Over',
    '-composite',
    `tmp/tcc-pig/mouth-${pose}.png`,
    '-compose',
    'Over',
    '-composite',
    '-resize',
    '384x128!',
    '-strip',
    '-quality',
    '72',
    file,
  ]);
  previews[pose] = 'data:image/webp;base64,' + (await readFile(file)).toString('base64');
}
await writeFile(
  'src/app/components/tcc-pig-slide/tcc-pig-fallback.ts',
  '// Generated by scripts/tcc-pig-slide/fallback.mjs from the approved pig layers.\n' +
    '// Inline complete previews survive network failure; detailed separate assets are unchanged.\n' +
    `export const PIG_REST_FALLBACK = ${JSON.stringify(previews.rest)};\n` +
    `export const PIG_KISS_FALLBACK = ${JSON.stringify(previews.kiss)};\n`,
);
